#!/bin/sh
# Shared commit-message checks used by the commit-msg hook, make scan, and
# behavioral regression tests.
#
# Policy: commits must not carry AI tool attribution (AI co-author trailers,
# "Generated with <tool>" lines, or agent session trailers/links). Authorship
# belongs to the humans who review and commit the change. AGENTS.md states the
# rule for agents; this file enforces it outside the model, because a written
# rule alone is easy to miss and `git commit --no-verify` skips local hooks.

# Print the offending lines of a message read on stdin and fail when it
# contains AI attribution.
commit_policy_check_stream() {
	# Product names are listed explicitly instead of a bare "ai" so ordinary
	# prose such as "files generated by AI tools" passes. Trailers cover the
	# credit forms tools and kernel-style workflows use besides Co-authored-by;
	# the "generated" rule also matches the hyphenated `Generated-by:` form.
	commit_policy_hits=$(grep -inE \
		-e '^(co-authored|co-developed|assisted|generated)-by:.*(claude|anthropic|codex|openai|chatgpt|copilot|gemini|cursor)' \
		-e '^(claude|codex|ai|agent)-session:' \
		-e 'generated[ -](with|by):? (.*[^a-z])?(claude|codex|chatgpt|copilot|gemini|cursor)([^a-z]|$)' \
		-e 'claude\.ai/code/session_') || true

	[ -n "${commit_policy_hits}" ] || return 0

	printf '%s\n' 'commit-msg: AI attribution is not allowed (see docs/gitops-conventions.md):' >&2
	printf '%s\n' "${commit_policy_hits}" >&2
	return 1
}

# Check the commit-msg hook's editor buffer. Comment lines and the
# `git commit -v` diff below the scissors line are ignored, because Git's
# default cleanup drops them before recording the message.
check_commit_message_file() {
	# Blank (rather than delete) comment lines so reported line numbers still
	# match the message file.
	sed -e '/^# -* >8 -*$/,$d' -e 's/^#.*//' "$1" | commit_policy_check_stream
}

# Check a message exactly as Git recorded it. No cleanup here: a commit made
# with `--cleanup=verbatim` or through the GitHub API can store comment and
# scissors lines, and trailers after them still count as attribution.
check_recorded_commit_message_file() {
	commit_policy_check_stream <"$1"
}

# Choose the commits to check and print them as `git rev-list` arguments.
# - CI passes COMMIT_POLICY_BASE/COMMIT_POLICY_HEAD (the pushed or PR range).
# - An unknown base (first push of a branch, force-pushed history, or the
#   all-zero SHA GitHub sends for new refs) falls back to the head's full
#   history, so nothing slips through unchecked.
# - Locally, without CI variables, check commits since the remote default
#   branch, or only HEAD when there is no remote.
commit_policy_rev_list_args() {
	commit_policy_head=${COMMIT_POLICY_HEAD:-HEAD}
	commit_policy_base=${COMMIT_POLICY_BASE:-}

	if [ -z "${commit_policy_base}" ] && [ -z "${COMMIT_POLICY_HEAD:-}" ]; then
		commit_policy_remote_default=$(git symbolic-ref -q --short refs/remotes/origin/HEAD 2>/dev/null) ||
			commit_policy_remote_default=origin/main
		if git rev-parse -q --verify "${commit_policy_remote_default}^{commit}" >/dev/null 2>&1; then
			commit_policy_base=$(git merge-base "${commit_policy_head}" "${commit_policy_remote_default}") || commit_policy_base=''
		fi
		if [ -z "${commit_policy_base}" ]; then
			printf '%s\n' '--max-count=1' "${commit_policy_head}"
			return 0
		fi
	fi

	if [ -n "${commit_policy_base}" ] && git cat-file -e "${commit_policy_base}^{commit}" 2>/dev/null; then
		printf '%s\n' "${commit_policy_base}..${commit_policy_head}"
	else
		printf '%s\n' "${commit_policy_head}"
	fi
}

# Recheck every commit in range with the hook logic. CI runs this because local
# hooks are opt-in and can be skipped; GitHub squash merges also copy PR text
# into the commit message, so attribution in a PR body is caught on main.
check_commit_attribution_policy() {
	if ! git rev-parse --git-dir >/dev/null 2>&1; then
		printf '%s\n' 'Not a Git checkout; skipping commit attribution check'
		return 0
	fi

	# Word splitting is intended: the helper prints one rev-list argument per line.
	# shellcheck disable=SC2046
	set -- $(commit_policy_rev_list_args)
	# Resolve the range before looping: a failing command substitution in a
	# `for` list is ignored even under `set -e`, so an unknown head (a shallow
	# clone or a bad CI event field) would otherwise check zero commits and pass.
	if ! commit_policy_commits=$(git rev-list "$@"); then
		printf 'commit policy: cannot list commits for %s\n' "$*" >&2
		return 1
	fi
	commit_policy_message_file=$(mktemp)
	commit_policy_status=0
	for commit_policy_commit in ${commit_policy_commits}; do
		git log -1 --format=%B "${commit_policy_commit}" >"${commit_policy_message_file}"
		if ! check_recorded_commit_message_file "${commit_policy_message_file}" 2>"${commit_policy_message_file}.err"; then
			printf 'commit %s:\n' "${commit_policy_commit}" >&2
			cat "${commit_policy_message_file}.err" >&2
			commit_policy_status=1
		fi
	done
	rm -f "${commit_policy_message_file}" "${commit_policy_message_file}.err"
	return "${commit_policy_status}"
}
